  const previous = {p1:-1,p2:-1,reviews:[]};
  function randomIndex(length,last){
    if(length<2) return 0;
    let i=Math.floor(Math.random()*length);
    if(i===last) i=(i+1+Math.floor(Math.random()*(length-1)))%length;
    return i;
  }
  function getStyles(containerId){
    return Array.from(document.querySelectorAll('#'+containerId+' .chip.selected')).map(x=>x.textContent.trim()).filter(Boolean);
  }
  function traitFor(styles){
    const known=styles.filter(x=>TRAITS[x]);
    if(!known.length) return 'выразительным звучанием, которое не любит оставаться незамеченным';
    return TRAITS[known[Math.floor(Math.random()*known.length)]];
  }
  function makePortrait(name, role, styles, slot){
    const i=randomIndex(PORTRAITS.length,previous[slot]);
    previous[slot]=i;
    let text=PORTRAITS[i](name);
    const trait=traitFor(styles);
    const roleText=role&&role!=='—'?` В группе этому человеку естественно быть ${role.toLowerCase()}.`:' ';
    const additions=[
      ` Его выбор особенно тянется к ${trait}.`,
      ` В его музыкальном мире важнее всего ${trait}.`,
      ` Неудивительно, что его тянет к ${trait}.`,
      ` В этом вкусе хорошо слышно стремление к ${trait}.`,
      ` Поэтому особенно органично для него ${trait}.`
    ];
    text+=additions[Math.floor(Math.random()*additions.length)]+roleText;
    return text;
  }
  function chooseReviewCount(){
    const r=Math.random();
    return r<0.22?3:(r<0.78?4:5);
  }
  function renderReviews(){
    const grid=document.querySelector('.review-grid');
    if(!grid) return;
    const band=document.querySelector('.band-name')?.textContent.trim()||'эта группа';
    const count=chooseReviewCount();
    let pool=REVIEWS.map((_,i)=>i).filter(i=>!previous.reviews.includes(i));
    if(pool.length<count) pool=REVIEWS.map((_,i)=>i);
    pool.sort(()=>Math.random()-0.5);
    const chosen=pool.slice(0,count);
    previous.reviews=chosen;
    grid.innerHTML=chosen.map(i=>`<div class="review"><h4>${REVIEWS[i][0]}</h4><p>${REVIEWS[i][1](band)}</p></div>`).join('');
    grid.style.gridTemplateColumns=count===3?'repeat(2,1fr)':'repeat(2,1fr)';
    if(count===5) grid.lastElementChild.style.gridColumn='1 / -1';
  }
  function apply(){
    const people=document.querySelectorAll('.result-person');
    if(people.length>=2){
      const n1=people[0].querySelector('.result-person-name')?.textContent.trim()||'Персонаж I';
      const n2=people[1].querySelector('.result-person-name')?.textContent.trim()||'Персонаж II';
      const r1=document.getElementById('role1')?.value||'';
      const r2=document.getElementById('role2')?.value||'';
      const p1=people[0].querySelector('.character-profile p');
      const p2=people[1].querySelector('.character-profile p');
      if(p1) p1.textContent=makePortrait(n1,r1,getStyles('styles1'),'p1');
      if(p2) p2.textContent=makePortrait(n2,r2,getStyles('styles2'),'p2');
    }
    renderReviews();
  }
